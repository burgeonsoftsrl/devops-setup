// Writes src/environments/environment.ts from the API_URL env var so the
// gateway URL is configured in Cloudflare Pages, not hard-coded in the repo.
import { writeFileSync } from 'node:fs';

const apiUrl = (process.env.API_URL ?? '').trim().replace(/\/+$/, '');
if (!apiUrl) {
  console.warn('[set-api-url] API_URL not set; keeping existing environment.ts');
  process.exit(0);
}
writeFileSync(
  new URL('../src/environments/environment.ts', import.meta.url),
  `// Generated by scripts/set-api-url.mjs\nexport const environment = {\n  apiUrl: ${JSON.stringify(apiUrl)},\n};\n`,
);
console.log(`[set-api-url] apiUrl = ${apiUrl}`);
